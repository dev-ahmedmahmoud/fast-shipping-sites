#!/usr/bin/env node
// Packs public/ into src/static.js, so the Worker serves the app itself (no separate asset upload).
import fs from 'node:fs';
const dir = new URL('../public/', import.meta.url);
const TYPES = { html: 'text/html; charset=utf-8', js: 'text/javascript; charset=utf-8', css: 'text/css; charset=utf-8', webmanifest: 'application/manifest+json', png: 'image/png' };
const files = {};
for (const name of fs.readdirSync(dir).sort()) {
  if (name.startsWith('_')) continue;
  const ext = name.split('.').pop();
  if (!TYPES[ext]) continue;
  const buf = fs.readFileSync(new URL(name, dir));
  files['/' + name] = ext === 'png' ? { type: TYPES[ext], b64: buf.toString('base64') } : { type: TYPES[ext], text: buf.toString('utf8') };
}
const headers = fs.readFileSync(new URL('_headers', dir), 'utf8');
const out = `// GENERATED by scripts/build-static.mjs from public/. Do not edit; run: npm run build\nexport const FILES = ${JSON.stringify(files)};\nexport const HEADERS_FILE = ${JSON.stringify(headers)};\n`;
fs.writeFileSync(new URL('../src/static.js', import.meta.url), out);
console.log(`packed ${Object.keys(files).length} files`);
